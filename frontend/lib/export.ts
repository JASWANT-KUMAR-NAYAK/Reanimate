
import type { AnalysisReport, Evidence, RoadmapItem } from "./types";

function section(title: string, items: RoadmapItem[]): string {
  if (!items.length) return `### ${title}\n\nNo tasks identified.\n`;

  return `### ${title}\n\n${items.map((item) => [
    `#### ${item.title}`,
    `- Priority: ${item.priority}`,
    `- Complexity: ${item.complexity}`,
    `- Suggested contributor: ${item.contributor_type}`,
    `- Description: ${item.description}`,
    `- Why it matters: ${item.reason}`,
    `- Expected outcome: ${item.expected_outcome}`,
    `- Evidence: ${item.evidence_ids.join(", ") || "None"}`,
  ].join("\n")).join("\n\n")}\n`;
}

function evidenceBlock(item: Evidence): string {
  return [
    `### ${item.id}`,
    `- Category: ${item.category}`,
    `- Type: ${item.kind}`,
    `- Value: ${String(item.observed_value ?? "Unavailable")}`,
    `- Source: ${item.source}`,
    `- Indicates: ${item.indicates}`,
    item.limitation ? `- Limitation: ${item.limitation}` : "",
  ].filter(Boolean).join("\n");
}

export function buildMarkdownReport(report: AnalysisReport): string {
  const repo = report.repository;
  const indicators = report.indicators.map((item) =>
    `| ${item.name} | ${item.score ?? "Unknown"} | ${item.level} | ${item.rationale} |`
  ).join("\n");

  const ai = report.ai_insights
    ? [
        "## AI maintainer briefing",
        report.ai_insights.summary,
        "",
        "### Findings",
        ...report.ai_insights.findings.map((item) =>
          `- **${item.title}** (${item.confidence} confidence): ${item.explanation}\n  Evidence: ${item.evidence_ids.join(", ")}`
        ),
        "",
        "### Opportunities",
        ...report.ai_insights.opportunities.map((item) =>
          `- **${item.title}** (${item.confidence} confidence): ${item.explanation}\n  Evidence: ${item.evidence_ids.join(", ")}`
        ),
        `\nModel: ${report.ai_insights.model}`,
      ].join("\n")
    : "## AI maintainer briefing\n\nAI insights were unavailable for this analysis.";

  return [
    `# Reanimate Report: ${repo.full_name}`,
    `Generated: ${new Date(report.generated_at).toLocaleString()}`,
    "",
    `Repository: ${repo.url}`,
    `Description: ${repo.description ?? "Not provided"}`,
    `Stars: ${repo.stars} | Forks: ${repo.forks}`,
    `Language: ${repo.language ?? "Unknown"} | License: ${repo.license ?? "Unknown"}`,
    `Maintenance status: ${report.maintenance_status}`,
    `Overall health: ${report.overall_score ?? "Unknown"}/100`,
    "",
    "## Health indicators",
    "| Indicator | Score | Level | Explanation |",
    "|---|---:|---|---|",
    indicators,
    "",
    ai,
    "",
    "## Revival roadmap",
    section("Immediate fixes", report.roadmap.immediate),
    section("Short-term improvements", report.roadmap.short_term),
    section("Long-term growth", report.roadmap.long_term),
    "## Evidence",
    report.evidence.map(evidenceBlock).join("\n\n"),
    "",
    "## Limitations",
    ...report.limitations.map((item) => `- ${item}`),
    "",
    "## Scoring methodology",
    ...report.methodology.map((item) => `- ${item}`),
    "",
    "---",
    "Generated by Reanimate — Evidence-backed open-source repository revival.",
  ].join("\n");
}

export function downloadMarkdownReport(report: AnalysisReport): void {
  const content = buildMarkdownReport(report);
  const blob = new Blob([content], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");

  link.href = url;
  link.download = `reanimate-${report.repository.full_name.replace("/", "-")}.md`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}
