import { CalendarClock, Map, Sprout, Users, Zap, type LucideIcon } from "lucide-react";
import { COMPLEXITY_LABEL, PRIORITY_STYLE } from "@/lib/styles";
import type { Roadmap, RoadmapItem } from "@/lib/types";
import { Badge, Card, EvidenceRefs, Section } from "../ui";

const PHASES: { key: keyof Roadmap; title: string; blurb: string; icon: LucideIcon }[] = [
  { key: "immediate", title: "Immediate fixes", blurb: "Address these first. They block or discourage contributors.", icon: Zap },
  { key: "short_term", title: "Short-term improvements", blurb: "Raise project quality and make contributing easier.", icon: CalendarClock },
  { key: "long_term", title: "Long-term growth", blurb: "Build resilience and sustainable momentum.", icon: Sprout },
];

function TaskCard({ item, onEvidence }: { item: RoadmapItem; onEvidence: (id: string) => void }) {
  const priority = PRIORITY_STYLE[item.priority];
  return (
    <Card className="p-4">
      <div className="flex flex-wrap items-start justify-between gap-2">
        <h4 className="font-medium">{item.title}</h4>
        <div className="flex flex-wrap items-center gap-1.5">
          <Badge tone={priority.tone}>{priority.label}</Badge>
          <Badge>{COMPLEXITY_LABEL[item.complexity]}</Badge>
        </div>
      </div>
      <p className="mt-2 text-sm text-muted">{item.description}</p>
      <dl className="mt-3 grid gap-3 text-sm sm:grid-cols-2">
        <div>
          <dt className="text-xs text-subtle">Why this matters</dt>
          <dd className="mt-0.5">{item.reason}</dd>
        </div>
        <div>
          <dt className="text-xs text-subtle">Expected outcome</dt>
          <dd className="mt-0.5">{item.expected_outcome}</dd>
        </div>
      </dl>
      <div className="mt-3 flex flex-wrap items-center justify-between gap-3 border-t border-line pt-3">
        <EvidenceRefs ids={item.evidence_ids} onSelect={onEvidence} />
        <span className="inline-flex items-center gap-1.5 text-xs text-muted">
          <Users className="size-3.5" aria-hidden />
          Suggested contributor: {item.contributor_type}
        </span>
      </div>
    </Card>
  );
}

export function RoadmapSection({ roadmap, onEvidence }: { roadmap: Roadmap; onEvidence: (id: string) => void }) {
  return (
    <Section
      id="roadmap"
      title="Revival roadmap"
      icon={Map}
      description="Tasks are generated by deterministic rules from this repository's evidence, ordered by priority within each phase."
    >
      <div className="space-y-8">
        {PHASES.map(({ key, title, blurb, icon: Icon }) => (
          <div key={key}>
            <div className="mb-3 flex flex-wrap items-baseline gap-x-3">
              <h3 className="flex items-center gap-2 font-semibold">
                <Icon className="size-4 text-accent" aria-hidden />
                {title}
                <span className="rounded-full bg-surface-2 px-2 text-xs font-normal text-muted">{roadmap[key].length}</span>
              </h3>
              <p className="text-sm text-subtle">{blurb}</p>
            </div>
            {roadmap[key].length === 0 ? (
              <p className="rounded-lg border border-dashed border-line p-4 text-sm text-subtle">No tasks were triggered for this phase by the collected evidence.</p>
            ) : (
              <div className="space-y-3">
                {roadmap[key].map((item) => (
                  <TaskCard key={item.title} item={item} onEvidence={onEvidence} />
                ))}
              </div>
            )}
          </div>
        ))}
      </div>
    </Section>
  );
}
